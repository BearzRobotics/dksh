//! Turns the vendored Unicode Character Database files into compact range
//! tables for the regex engine (SPEC 5.12). Nothing is downloaded: updating
//! Unicode means replacing the files under `data/ucd/`.
//!
//! usage: gen_unicode <ucd dir> <output.zig>

const std = @import("std");
const sys = @import("sys");

const gpa = std.heap.page_allocator;

const Range = struct { lo: u32, hi: u32, v: u32 };

const categories = [_][]const u8{
    "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
    "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co",
};

fn die(comptime fmt: []const u8, args: anytype) noreturn {
    sys.write(2, std.fmt.allocPrint(gpa, "gen_unicode: " ++ fmt ++ "\n", args) catch "gen_unicode: error\n");
    sys.exit(1);
}

fn readUcd(dir: []const u8, name: []const u8) []const u8 {
    const path = std.fs.path.join(gpa, &.{ dir, name }) catch die("oom", .{});
    return sys.readFile(gpa, path) catch die("cannot read {s}", .{path});
}

fn hex(s: []const u8) u32 {
    return std.fmt.parseInt(u32, std.mem.trim(u8, s, " \t"), 16) catch die("bad hex '{s}'", .{s});
}

/// Parse "XXXX" or "XXXX..YYYY" into lo/hi.
fn parseRange(s: []const u8) [2]u32 {
    if (std.mem.indexOf(u8, s, "..")) |i| return .{ hex(s[0..i]), hex(s[i + 2 ..]) };
    const v = hex(s);
    return .{ v, v };
}

fn lessRange(_: void, a: Range, b: Range) bool {
    return a.lo < b.lo;
}

/// Sort and merge touching ranges that carry the same value.
fn normalize(list: *std.ArrayList(Range)) void {
    std.mem.sort(Range, list.items, {}, lessRange);
    var out: std.ArrayList(Range) = .empty;
    for (list.items) |r| {
        if (out.items.len > 0) {
            const last = &out.items[out.items.len - 1];
            if (last.v == r.v and last.hi + 1 >= r.lo) {
                last.hi = @max(last.hi, r.hi);
                continue;
            }
        }
        out.append(gpa, r) catch die("oom", .{});
    }
    list.* = out;
}

fn emitRanges(out: *std.ArrayList(u8), name: []const u8, list: []const Range, with_value: bool) void {
    out.print(gpa, "pub const {s} = [_][3]u32{{\n", .{name}) catch die("oom", .{});
    for (list) |r| {
        out.print(gpa, "    .{{ 0x{X}, 0x{X}, {d} }},\n", .{ r.lo, r.hi, if (with_value) r.v else 0 }) catch die("oom", .{});
    }
    out.appendSlice(gpa, "};\n\n") catch die("oom", .{});
}

/// Collect ranges for one property from a PropList-style file.
fn propRanges(text: []const u8, prop: []const u8) std.ArrayList(Range) {
    var list: std.ArrayList(Range) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = if (std.mem.indexOfScalar(u8, raw, '#')) |h| raw[0..h] else raw;
        if (std.mem.trim(u8, line, " \t\r").len == 0) continue;
        var f = std.mem.splitScalar(u8, line, ';');
        const rng = f.next() orelse continue;
        const name = std.mem.trim(u8, f.next() orelse continue, " \t\r");
        if (!std.mem.eql(u8, name, prop)) continue;
        const r = parseRange(std.mem.trim(u8, rng, " \t"));
        list.append(gpa, .{ .lo = r[0], .hi = r[1], .v = 0 }) catch die("oom", .{});
    }
    normalize(&list);
    return list;
}

pub fn main(init: std.process.Init.Minimal) void {
    const argv = init.args.vector;
    if (argv.len != 3) die("usage: gen_unicode <ucd dir> <output.zig>", .{});
    const dir: []const u8 = std.mem.span(argv[1]);
    const out_path: []const u8 = std.mem.span(argv[2]);

    var out: std.ArrayList(u8) = .empty;
    const version = std.mem.trim(u8, readUcd(dir, "VERSION"), " \t\r\n");
    out.print(gpa, "//! Generated by build/gen_unicode.zig from Unicode {s}. Do not edit.\n\n", .{version}) catch die("oom", .{});
    out.print(gpa, "pub const version = \"{s}\";\n\n", .{version}) catch die("oom", .{});

    // ---- General categories (UnicodeData.txt)
    var gc: std.ArrayList(Range) = .empty;
    {
        const text = readUcd(dir, "UnicodeData.txt");
        var lines = std.mem.splitScalar(u8, text, '\n');
        var first: ?u32 = null;
        while (lines.next()) |line| {
            if (line.len == 0) continue;
            var f = std.mem.splitScalar(u8, line, ';');
            const code = hex(f.next().?);
            const name = f.next().?;
            const cat = f.next().?;
            var idx: ?u32 = null;
            for (categories, 0..) |c, i| {
                if (std.mem.eql(u8, c, cat)) idx = @intCast(i);
            }
            const v = idx orelse continue; // Cn is "absent"
            if (std.mem.endsWith(u8, name, ", First>")) {
                first = code;
                continue;
            }
            const lo = if (std.mem.endsWith(u8, name, ", Last>")) first.? else code;
            gc.append(gpa, .{ .lo = lo, .hi = code, .v = v }) catch die("oom", .{});
        }
        normalize(&gc);
    }
    out.appendSlice(gpa, "pub const category_names = [_][]const u8{") catch die("oom", .{});
    for (categories) |c| out.print(gpa, "\"{s}\", ", .{c}) catch die("oom", .{});
    out.appendSlice(gpa, "};\n\n") catch die("oom", .{});
    emitRanges(&out, "categories", gc.items, true);

    // ---- Scripts (Scripts.txt)
    var scripts: std.ArrayList(Range) = .empty;
    var script_names: std.ArrayList([]const u8) = .empty;
    {
        const text = readUcd(dir, "Scripts.txt");
        var lines = std.mem.splitScalar(u8, text, '\n');
        while (lines.next()) |raw| {
            const line = if (std.mem.indexOfScalar(u8, raw, '#')) |h| raw[0..h] else raw;
            if (std.mem.trim(u8, line, " \t\r").len == 0) continue;
            var f = std.mem.splitScalar(u8, line, ';');
            const rng = parseRange(std.mem.trim(u8, f.next().?, " \t"));
            const name = std.mem.trim(u8, f.next() orelse continue, " \t\r");
            var id: ?u32 = null;
            for (script_names.items, 0..) |n, i| {
                if (std.mem.eql(u8, n, name)) id = @intCast(i);
            }
            if (id == null) {
                id = @intCast(script_names.items.len);
                script_names.append(gpa, gpa.dupe(u8, name) catch die("oom", .{})) catch die("oom", .{});
            }
            scripts.append(gpa, .{ .lo = rng[0], .hi = rng[1], .v = id.? }) catch die("oom", .{});
        }
        normalize(&scripts);
    }
    out.appendSlice(gpa, "pub const script_names = [_][]const u8{\n") catch die("oom", .{});
    for (script_names.items) |n| out.print(gpa, "    \"{s}\",\n", .{n}) catch die("oom", .{});
    out.appendSlice(gpa, "};\n\n") catch die("oom", .{});
    emitRanges(&out, "scripts", scripts.items, true);

    // ---- White_Space / Join_Control (PropList.txt), Alphabetic (DerivedCoreProperties.txt)
    {
        const text = readUcd(dir, "PropList.txt");
        const ws = propRanges(text, "White_Space");
        emitRanges(&out, "white_space", ws.items, false);
        const jc = propRanges(text, "Join_Control");
        emitRanges(&out, "join_control", jc.items, false);
        const dcp = readUcd(dir, "DerivedCoreProperties.txt");
        const al = propRanges(dcp, "Alphabetic");
        emitRanges(&out, "alphabetic", al.items, false);
    }

    // ---- Simple case folding (CaseFolding.txt: statuses C and S)
    {
        const text = readUcd(dir, "CaseFolding.txt");
        out.appendSlice(gpa, "/// Pairs of (code point, simple case fold), sorted by code point.\npub const case_fold = [_][2]u32{\n") catch die("oom", .{});
        var pairs: std.ArrayList([2]u32) = .empty;
        var lines = std.mem.splitScalar(u8, text, '\n');
        while (lines.next()) |raw| {
            const line = if (std.mem.indexOfScalar(u8, raw, '#')) |h| raw[0..h] else raw;
            if (std.mem.trim(u8, line, " \t\r").len == 0) continue;
            var f = std.mem.splitScalar(u8, line, ';');
            const from = hex(f.next().?);
            const status = std.mem.trim(u8, f.next() orelse continue, " \t");
            if (!(std.mem.eql(u8, status, "C") or std.mem.eql(u8, status, "S"))) continue;
            const to = hex(f.next().?);
            pairs.append(gpa, .{ from, to }) catch die("oom", .{});
        }
        std.mem.sort([2]u32, pairs.items, {}, struct {
            fn lt(_: void, a: [2]u32, b: [2]u32) bool {
                return a[0] < b[0];
            }
        }.lt);
        for (pairs.items) |p| out.print(gpa, "    .{{ 0x{X}, 0x{X} }},\n", .{ p[0], p[1] }) catch die("oom", .{});
        out.appendSlice(gpa, "};\n") catch die("oom", .{});
    }

    sys.writeFile(gpa, out_path, out.items, false) catch die("cannot write {s}", .{out_path});
}
